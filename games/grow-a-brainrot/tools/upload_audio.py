"""
Uploads assets/audio/*.wav to Roblox with Open Cloud and writes the new asset
IDs into src/shared/Config/SoundIds.luau.

Setup (once):
  1. https://create.roblox.com/dashboard/credentials -> Create API Key
     - Access: "Assets API" with Read + Write
     - Accepted IP: your IP (or 0.0.0.0/0 for testing)
  2. Find your user ID (the number in your roblox.com profile URL).

Run:
  set ROBLOX_API_KEY=...      (PowerShell: $env:ROBLOX_API_KEY="...")
  set ROBLOX_USER_ID=...
  python tools/upload_audio.py            # uploads everything missing an ID
  python tools/upload_audio.py pop zap    # (re)uploads just these

Uploads go through Roblox moderation; new audio can take a little while to
become playable. Monthly audio upload limits apply to your account.
"""

import json
import os
import re
import sys
import time
import urllib.request
import uuid

ROOT = os.path.join(os.path.dirname(__file__), "..")
AUDIO = os.path.join(ROOT, "assets", "audio")
IDS_FILE = os.path.join(ROOT, "src", "shared", "Config", "SoundIds.luau")
API = "https://apis.roblox.com/assets/v1"


def read_ids():
    ids = {}
    if os.path.exists(IDS_FILE):
        for name, value in re.findall(r'(\w+)\s*=\s*"(rbxassetid://\d+)"', open(IDS_FILE, encoding="utf-8").read()):
            ids[name] = value
    return ids


def write_ids(ids):
    lines = [
        "-- GENERATED by tools/upload_audio.py. Uploaded Roblox asset IDs for assets/audio/*.wav.",
        "-- Missing names fall back to built-in sounds (see Config/Sounds.luau).",
        "",
        "return {",
    ]
    for name in sorted(ids):
        lines.append(f'\t{name} = "{ids[name]}",')
    lines.append("}")
    open(IDS_FILE, "w", encoding="utf-8").write("\n".join(lines) + "\n")


def request(method, url, key, body=None, content_type=None):
    req = urllib.request.Request(url, data=body, method=method)
    req.add_header("x-api-key", key)
    if content_type:
        req.add_header("Content-Type", content_type)
    with urllib.request.urlopen(req) as res:
        return json.loads(res.read())


def upload(path, name, key, user_id):
    boundary = uuid.uuid4().hex
    meta = {
        "assetType": "Audio",
        "displayName": f"GrowABrainrot_{name}",
        "description": "Grow a Brainrot sound effect (original, synthesized).",
        "creationContext": {"creator": {"userId": str(user_id)}},
    }
    data = open(path, "rb").read()
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{json.dumps(meta)}\r\n"
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{name}.wav\"\r\n"
        f"Content-Type: audio/wav\r\n\r\n"
    ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
    op = request("POST", API + "/assets", key, body, f"multipart/form-data; boundary={boundary}")
    op_id = op.get("operationId") or op["path"].split("/")[-1]
    for _ in range(60):
        status = request("GET", f"{API}/operations/{op_id}", key)
        if status.get("done"):
            asset_id = status["response"]["assetId"]
            return f"rbxassetid://{asset_id}"
        time.sleep(2)
    raise RuntimeError("timed out waiting for upload " + name)


def main():
    key = os.environ.get("ROBLOX_API_KEY")
    user_id = os.environ.get("ROBLOX_USER_ID")
    if not key or not user_id:
        sys.exit("Set ROBLOX_API_KEY and ROBLOX_USER_ID first (see the top of this file).")
    ids = read_ids()
    wanted = sys.argv[1:]
    for file in sorted(os.listdir(AUDIO)):
        if not file.endswith(".wav"):
            continue
        name = file[:-4]
        if (wanted and name not in wanted) or (not wanted and name in ids):
            continue
        try:
            ids[name] = upload(os.path.join(AUDIO, file), name, key, user_id)
            print(f"  {name}: {ids[name]}")
            write_ids(ids)  # save as we go
        except Exception as e:  # keep going; report at the end
            print(f"  {name}: FAILED {e}")
    print("Done. IDs are in", os.path.relpath(IDS_FILE, ROOT))


if __name__ == "__main__":
    main()
